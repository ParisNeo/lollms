import json
import os
import secrets
from typing import Any, Dict, Optional
from sqlalchemy.orm import Session
from backend.db.models.config import GlobalConfig

# Published values shipped in historical releases. These are public knowledge and
# MUST never be accepted as a real signing key in production.
_LEGACY_INSECURE_SECRET_KEYS = frozenset({
    "a_very_secret_key_that_should_be_changed_for_production",
    "a_very_secret_key_for_flask_sessions_or_jwt",
    "my_super_secret_safe_store_key_CHANGE_ME",
})

# Minimum length for a SECRET_KEY to be considered safe for JWT HS256 signing.
_MIN_SECRET_KEY_LENGTH = 32

# DB key under which an auto-generated SECRET_KEY is persisted for retro-compatibility.
_AUTO_SECRET_KEY_SETTING = "__lollms_autogenerated_secret_key__"

def _is_secure_secret_key(value: Optional[str]) -> bool:
    """Return True if value is a non-placeholder, sufficiently long secret."""
    if not value or not isinstance(value, str):
        return False
    if value in _LEGACY_INSECURE_SECRET_KEYS:
        return False
    if len(value) < _MIN_SECRET_KEY_LENGTH:
        return False
    return True


class _Settings:
    _instance = None
    _settings_cache: Dict[str, Any] = {}
    _is_loaded = False

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(_Settings, cls).__new__(cls)
        return cls._instance

    def load_from_db(self, db: Session):
        """
        Loads all settings from the database into the cache.
        This method is now safe to be called by multiple processes; it will only execute
        the loading and logging logic once per process lifecycle thanks to the _is_loaded flag.
        """
        if self._is_loaded:
            return

        try:
            configs = db.query(GlobalConfig).all()
            if not configs:
                print("WARNING: No settings found in 'global_configs' table.")
                self._settings_cache = {}
            else:
                for config in configs:
                    try:
                        # print(config.key)
                        # print(config.value)
                        # if config.key == "export_to_docx_enabled":
                        #     print("Found export_to_docx_enabled setting")
                        # Value from DB is expected to be a JSON string like '{"value": ..., "type": ...}'
                        structured_data = json.loads(config.value)
                        
                        # Handle case where the value itself is a JSON string (double-encoded)
                        if isinstance(structured_data, str):
                            structured_data = json.loads(structured_data)
                        
                        # Now, we should have a dict. Extract the actual value.
                        if isinstance(structured_data, dict) and 'value' in structured_data:
                            val = structured_data.get('value')
                            val_type = structured_data.get('type', 'string')

                            if val_type == 'integer':
                                self._settings_cache[config.key] = int(val) if val is not None else 0
                            elif val_type == 'float':
                                self._settings_cache[config.key] = float(val) if val is not None else 0.0
                            elif val_type == 'boolean':
                                self._settings_cache[config.key] = str(val).lower() in ('true', '1', 'yes', 'on')
                            elif val_type == 'json':
                                if isinstance(val, str):
                                    self._settings_cache[config.key] = json.loads(val) if val else {}
                                else:
                                    self._settings_cache[config.key] = val  # It's already a dict/list
                            else:  # string, text, etc.
                                self._settings_cache[config.key] = val
                        else:
                            # Fallback for old/unstructured JSON data (e.g., just "some_value" or a raw JSON dict)
                            self._settings_cache[config.key] = structured_data
                    except (json.JSONDecodeError, TypeError, ValueError):
                        # If it's not valid JSON, treat it as a raw string
                        self._settings_cache[config.key] = config.value

            self._ensure_secure_secret_key(db)

            print(f"INFO: Loaded {len(self._settings_cache)} settings into cache.")
            self._is_loaded = True
        except Exception as e:
            print(f"CRITICAL: An unexpected error occurred while loading settings: {e}.")
            self._is_loaded = False

    def _ensure_secure_secret_key(self, db: Session) -> None:
        """
        Guarantee that SECRET_KEY resolves to a strong, non-public value.

        Resolution order:
          1. Environment variable SECRET_KEY (if secure) — highest priority.
          2. Cached/DB SECRET_KEY (if secure) — preserves existing installations.
          3. Auto-generated key persisted in DB — retro-compatible fallback for fresh
             or legacy installs that shipped with an insecure default.

        Insecure/placeholder defaults (the well-known published strings) are rejected
        so that a forged JWT signed with the old public key can no longer be accepted.
        """
        env_key = os.getenv("SECRET_KEY")
        if _is_secure_secret_key(env_key):
            self._settings_cache["SECRET_KEY"] = env_key
            return

        cached_key = self._settings_cache.get("SECRET_KEY")
        if isinstance(cached_key, dict) and "value" in cached_key:
            cached_key = cached_key["value"]

        if _is_secure_secret_key(cached_key):
            # Persist back so the value survives restarts even if the DB row was
            # corrupted with a dict wrapper or an old placeholder.
            self._persist_secret_key(db, cached_key)
            return

        # No usable key: reuse a previously auto-generated one if present, else
        # create a new cryptographically strong key.
        autogenerated = self._settings_cache.get(_AUTO_SECRET_KEY_SETTING)
        if not _is_secure_secret_key(autogenerated):
            autogenerated = secrets.token_urlsafe(64)
            print(
                "WARNING: SECRET_KEY is unset or uses an insecure default. "
                "An auto-generated key has been created and stored; user sessions "
                "will be invalidated on restart if the DB row cannot be persisted. "
                "Set SECRET_KEY explicitly in production."
            )

        self._settings_cache["SECRET_KEY"] = autogenerated
        self._settings_cache[_AUTO_SECRET_KEY_SETTING] = autogenerated
        self._persist_secret_key(db, autogenerated)

    @staticmethod
    def _persist_secret_key(db: Session, key: str) -> None:
        """Best-effort persistence of a resolved SECRET_KEY; failures are non-fatal."""
        try:
            config = db.query(GlobalConfig).filter(GlobalConfig.key == "SECRET_KEY").first()
            payload = json.dumps({"value": key, "type": "string"})
            if config is None:
                db.add(GlobalConfig(key="SECRET_KEY", value=payload))
            else:
                config.value = payload
            db.commit()
        except Exception as e:
            db.rollback()
            print(f"WARNING: Could not persist SECRET_KEY to database: {e}")

    def get(self, key: str, default: Optional[Any] = None) -> Any:
        # if not self._is_loaded:
        #    print("WARNING: Settings accessed before being loaded. This may indicate an issue.")

        value = self._settings_cache.get(key, default)

        # FINAL SAFEGUARD: If a dictionary wrapper was somehow cached, extract the primitive value.
        if isinstance(value, dict) and 'value' in value:
            return value['value']

        return value

    def all(self) -> Dict[str, Any]:
        return self._settings_cache.copy()

    def refresh(self, db: Session):
        """Forces a reload of the settings from the database."""
        print("INFO: Refreshing global settings cache from database...")
        self._is_loaded = False
        self._settings_cache.clear()
        self.load_from_db(db)

settings = _Settings()