import { marked } from 'marked';

const mathPlaceholders = new Map();
let mathCounter = 0;

// Regex to match fenced code blocks (``` or ~~~) to protect their content
const FENCE_REGEX = /^(```|~~~)[\w-]*\n[\s\S]*?\n\1$/gm;

function protectMath(text) {
    if (!text) return text;
    mathCounter = 0;
    mathPlaceholders.clear();

    return text.replace(/(\$\$[\s\S]*?\$\$|\$[\s\S]*?\$)/g, (match) => {
        const placeholder = `<!--MATH_PLACEHOLDER_${mathCounter}-->`;
        mathPlaceholders.set(placeholder, match);
        mathCounter++;
        return placeholder;
    });
}

function unprotectHtml(html) {
    if (!html || mathPlaceholders.size === 0) return html;
    let result = html;
    for (const [placeholder, original] of mathPlaceholders.entries()) {
        const regex = new RegExp(placeholder.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&'), 'g');
        result = result.replace(regex, original);
    }
    return result;
}

function escapeHtml(str) {
    if (!str || typeof str !== 'string') return '';
    return str
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

// Custom extension to handle [N] citations
const citationExtension = {
  name: 'citation',
  level: 'inline',
  start(src) { 
    if (typeof src !== 'string') return -1;
    return src.match(/\[\d+\]/)?.index; 
  },
  tokenizer(src, tokens) {
    const rule = /^\[(\d+)\]/;
    const match = rule.exec(src);
    if (match) {
      return {
        type: 'citation',
        raw: match[0],
        index: match[1]
      };
    }
  },
  renderer(token) {
    return `<button class="citation-btn text-blue-500 hover:underline font-mono text-xs align-super cursor-pointer select-none px-0.5 rounded hover:bg-blue-100 dark:hover:bg-blue-900/30 transition-colors" data-index="${token.index}">[${token.index}]</button>`;
  }
};

// Strict isolation: Escape raw HTML tags so they NEVER inject arbitrary DOM elements outside sandboxes
const safeHtmlRenderer = {
    html(token) {
        const raw = typeof token === 'string' ? token : (token.text || token.raw || '');
        if (!raw) return '';

        // Preserve math placeholders
        if (/^<!--MATH_PLACEHOLDER_\d+-->$/.test(raw.trim())) {
            return raw;
        }

        // Preserve fence placeholders (should be handled by replace logic before returning)
        if (/^<!--FENCE_PLACEHOLDER_\d+-->$/.test(raw.trim())) {
            return raw;
        }

        // Preserve status comments
        if (/^<!--\s*status:[a-zA-Z0-9_-]+\s*-->$/.test(raw.trim())) {
            return raw;
        }

        // CRITICAL FIX: Escape lollms_form tags inside fences (they should be plain text)
        if (/^&lt;lollms_form.*&lt;\/lollms_form&gt;$/.test(raw.trim())) {
            return raw; // Already escaped, leave as raw text
        }

        // Allow inline-xml-tag codes generated by MessageContentRenderer
        if (/^<code\s+class=["']inline-xml-tag[^"']*["'][^>]*>[\s\S]*?<\/code>$/i.test(raw.trim())) {
            return raw;
        }

        // Allow safe inline text-level formatting tags without dangerous classes or styles
        if (/^<\/?(br|b|i|strong|em|code|kbd|del|s|strike|sub|sup)\b[^>]*>$/i.test(raw.trim())) {
            if (/\b(fixed|absolute|z-\d+|inset-|style=)\b/i.test(raw)) {
                return escapeHtml(raw);
            }
            return raw;
        }

        // Allow safe container tags for structure (no scripts/inputs)
        if (/^<\/?(div|section|article|header|footer|main|nav|aside|span|p|h[1-6]|ul|ol|li|dl|dt|dd|blockquote|pre|figure|figcaption|table|thead|tbody|tr|th|td)\b[^>]*>$/i.test(raw.trim())) {
             return raw;
        }

        // Escape all other raw HTML tags (script, style, link, iframe etc are removed/parsed securely elsewhere or sanitized here)
        return escapeHtml(raw);
    }
};

marked.use({ 
    extensions: [citationExtension],
    renderer: safeHtmlRenderer
});

function wrapNakedCode(text) {
    if (!text) return text;
    
    // If text looks like HTML markup or has style/canvas but no markdown fences
    if ((text.includes('<!DOCTYPE') || text.includes('<html') || text.includes('<style>') || text.includes('<canvas')) && !text.includes('```')) {
        return "```html\n" + text + "\n```";
    }
    
    const codeStartRegex = /^(import\s|from\s|const\s|function\s|def\s|class\s)/;
    if (codeStartRegex.test(text.trim()) && !text.includes('```')) {
        return "```\n" + text + "\n```";
    }
    
    return text;
}

function normalizeTables(text) {
    if (!text || typeof text !== 'string') return text;
    const tableSeparatorRegex = /^(\|?\s*:?-+:?\s*\|?)+$/m;
    if (!tableSeparatorRegex.test(text)) return text;

    const lines = text.split('\n');
    const result = [];

    for (let i = 0; i < lines.length; i++) {
        const line = lines[i];
        if (typeof line === 'string' && /^(\|?\s*:?-+:?\s*\|?)+$/.test(line.trim())) {
            if (i > 0 && typeof lines[i-1] === 'string' && lines[i-1].includes('|')) {
                if (i > 1 && typeof lines[i-2] === 'string' && lines[i-2].trim() !== '' && !lines[i-2].includes('|')) {
                    result.splice(result.length - 1, 0, '');
                }
            }
        }
        result.push(line);
    }
    return result.join('\n');
}

// NEW: Protect lollms_form tags inside code fences BEFORE parsing
function protectFormsInCodeBlocks(text) {
    if (!text) return text;
    
    // Find all code fences and escape lollms_form tags within them
    const codeBlockRegex = /(^\s*```[\s\S]*?^\s*```\s*?$)/gm;
    
    return text.replace(codeBlockRegex, (fence) => {
        // Escape any lollms_form tags inside this fence
        return fence.replace(/<lollms_form[\s\S]*?<\/lollms_form>/gi, (match) => {
            return match.replace(/</g, '&lt;').replace(/>/g, '&gt;');
        });
    });
}

function sanitizeDangerousTags(html) {
    if (!html) return html;

    // 1. Strip style, script, link blocks completely
    let clean = html.replace(/<style[\s\S]*?(?:<\/style>|$)/gi, '');
    clean = clean.replace(/<script[\s\S]*?(?:<\/script>|$)/gi, '');
    clean = clean.replace(/<link[^>]*?(?:>|$)/gi, '');

    // 2. Strip inline style attributes
    clean = clean.replace(/\sstyle\s*=\s*(?:"[^"]*"|'[^']*'|[^\s"'>]*)/gi, '');
    
    // 3. Neutralize inline event handlers
    clean = clean.replace(/\son\w+\s*=\s*(?:"[^"]*"|'[^']*'|[^\s"'>]*)/gi, '');

    // 4. Neutralize dangerous URL schemes
    clean = clean.replace(/\s(href|src)\s*=\s*["']?\s*(?:javascript:|vbscript:|data:text\/html)[^"'>\s]*/gi, ' $1="#"');

    // 5. Security guard for iframes: Only allow verified YouTube embeds
    clean = clean.replace(/<iframe\b([^>]*)>/gi, (match, attrs) => {
        const srcMatch = attrs.match(/src=["']([^"']+)["']/i);
        if (srcMatch && /^https:\/\/(?:www\.)?(?:youtube\.com|youtube-nocookie\.com)\/embed\/(?:videoseries\?list=[a-zA-Z0-9_-]{12,64}|[a-zA-Z0-9_-]{11}(?:\?[a-zA-Z0-9_=&-]*)?)$/i.test(srcMatch[1])) {
            return `<iframe ${attrs} sandbox="allow-scripts allow-presentation" loading="lazy" referrerpolicy="strict-origin-when-cross-origin">`;
        }
        return '<!-- [Untrusted iframe embed removed] -->';
    });

    // 6. Strip any layout-escaping classes from remaining elements
    clean = clean.replace(/\sclass\s*=\s*["']([^"']*)["']/gi, (match, classList) => {
        const safeClasses = classList.split(/\s+/).filter(c => {
            return !/^(fixed|absolute|inset-0|inset-x-0|inset-y-0|w-screen|h-screen|z-\d+|z-\[\d+\]|backdrop-blur.*)$/i.test(c);
        }).join(' ');
        return safeClasses ? ` class="${safeClasses}"` : '';
    });

    return clean;
}

export function parsedMarkdown(content, options = {}) {
    if (!content) return '';

    let metadata = options.metadata || null;
    let protectedContent = protectFormsInCodeBlocks(content); // FIRST: Escape forms in code blocks
    const placeholders = new Map();
    let phIndex = 0;

    // === YAML Frontmatter Detection & Extraction ===
    if (!metadata && typeof content === 'string' && content.startsWith('---')) {
        const metaMatch = content.match(/^(---\r?\n)([\s\S]*?)(\r?\n---\r?\n)([\s\S]*)$/);
        if (metaMatch) {
            try {
                const yamlStr = metaMatch[2];
                metadata = {};
                yamlStr.split('\n').forEach(line => {
                    const colonIdx = line.indexOf(':');
                    if (colonIdx > 0) {
                        const key = line.substring(0, colonIdx).trim();
                        const value = line.substring(colonIdx + 1).trim().replace(/^["']|["']$/g, '');
                        if (key) metadata[key] = value;
                    }
                });
                // Use capture group 4, which contains the content after frontmatter
                protectedContent = metaMatch[4].trim();
            } catch (e) {
                console.warn('Failed to parse YAML frontmatter:', e);
                protectedContent = content; // Fallback to original content on error
            }
        }
    }

    protectedContent = protectedContent.replace(FENCE_REGEX, (match) => {
        const ph = `<!--FENCE_PLACEHOLDER_${phIndex}-->`;
        placeholders.set(ph, match);
        phIndex++;
        return ph;
    });

    const trimmed = protectedContent.trim();
    if (trimmed.startsWith('graph ') || trimmed.startsWith('flowchart ') || trimmed.startsWith('sequenceDiagram') || trimmed.startsWith('classDiagram')) {
        if (!trimmed.startsWith('```')) {
            protectedContent = `\`\`\`mermaid\n${trimmed}\n\`\`\``;
        }
    }
  
    const wrappedContent = wrapNakedCode(protectedContent);
    
    let normalizedContent = wrappedContent;
    try {
        normalizedContent = normalizeTables(wrappedContent);
    } catch (e) {
        console.warn("Markdown pre-processing (tables) failed:", e);
    }

    const mathProtected = protectMath(normalizedContent);
    
    const rawHtml = marked.parse(mathProtected, { 
        gfm: true, 
        breaks: true, 
        mangle: false, 
        headerIds: false,
        smartypants: false 
    });

    // Restore Fences manually BEFORE final sanitization to protect code from being mangled.
    let finalHtml = rawHtml;
    for (const [ph, code] of placeholders.entries()) {
        const langMatch = code.match(/^```(\w+)/);
        const lang = langMatch ? langMatch[1] : '';
        const innerCode = code.replace(/^```\w*\n?/, '').replace(/\n?```$/, '');
        const safeCode = escapeHtml(innerCode);
        finalHtml = finalHtml.replace(ph, `<div class="code-block-skeleton my-2 p-2 rounded bg-gray-100 dark:bg-gray-800 font-mono text-sm overflow-x-auto" data-lang="${lang}"><pre>${safeCode}</pre></div>`);
    }
    
    return sanitizeDangerousTags(unprotectHtml(finalHtml));
}

function tokenizeMarkdownPart(markdown) {
    if (!markdown.trim()) {
        return [{ type: 'space', raw: markdown }];
    }
    const protectedText = protectMath(markdown);
    const markedTokens = Array.from(marked.lexer(protectedText, { mangle: false, smartypants: false }));

    return markedTokens.map(token => {
        const unprotectedToken = { ...token };
        if (unprotectedToken.raw) {
            unprotectedToken.raw = unprotectHtml(unprotectedToken.raw);
        }
        if (unprotectedToken.text) { 
            unprotectedToken.text = unprotectHtml(unprotectedToken.text);
        }
        return unprotectedToken;
    });
}

function customTokenizer(text) {
    if (!text) return [];

    const codeBlockRegex = /(^\s*```[\s\S]*?^\s*```\s*?$)/gm;
    const parts = text.split(codeBlockRegex);

    const tokens = [];

    for (let i = 0; i < parts.length; i++) {
        const part = parts[i];
        if (!part) continue;

        if (i % 2 === 1) {
            const codeBlockMatch = part.match(/^\s*```(\w*)\r?\n([\s\S]*?)\r?\n?^\s*```\s*?$/m);
            if (codeBlockMatch) {
                tokens.push({
                    type: 'code',
                    lang: codeBlockMatch[1] || 'plaintext',
                    text: codeBlockMatch[2],
                    raw: part
                });
            } else {
                tokens.push(...tokenizeMarkdownPart(part));
            }
        } else {
            tokens.push(...tokenizeMarkdownPart(part));
        }
    }
    return tokens;
}

export function getContentTokensWithMathProtection(text) {
    return customTokenizer(text);
}